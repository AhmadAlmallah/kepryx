def main() -> None:
    rows = build_rows()
    with OUTPUT_PATH.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    shadow_candidates = sum(
        row["edr_status"] == "None" or row["control_coverage"] == "none" for row in rows
    )
    print(f"Wrote {OUTPUT_PATH} ({len(rows)} assets, {shadow_candidates} CSV shadow candidates)")


if __name__ == "__main__":
    main()
