def _row(
    name: str,
    asset_type: str,
    os_name: str,
    ip: str,
    segment: str,
    edr: str,
    controls: str,
    exposure: str,
    auth: str,
    criticality: str,
    classification: str,
    last_patch: str,
    stack: str,
    cpe: str = "",
    dependencies: str = "",
    tags: str = "authoritative;demo",
    eol: str = "false",
) -> dict[str, str]:
    octet = int(ip.rsplit(".", 1)[1])
    mac = f"02:00:00:40:{octet // 256:02x}:{octet % 256:02x}"
    return {
        "name": name,
        "type": asset_type,
        "os": os_name,
        "ip": ip,
        "mac": mac,
        "segment": segment,
        "edr_status": edr,
        "control_coverage": controls,
        "network_exposure": exposure,
        "auth_method": auth,
        "criticality": criticality,
        "data_classification": classification,
        "last_patch": last_patch,
        "eol_status": eol,
        "software_stack": stack,
        "cpe": cpe,
        "dependencies": dependencies,
        "tags": tags,
    }


